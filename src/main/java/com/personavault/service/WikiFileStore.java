package com.personavault.service;

import java.io.IOException;
import java.io.UncheckedIOException;
import java.nio.charset.StandardCharsets;
import java.nio.file.AtomicMoveNotSupportedException;
import java.nio.file.Files;
import java.nio.file.Path;
import java.nio.file.StandardCopyOption;
import java.util.Optional;
import java.util.regex.Pattern;

import com.personavault.entity.WikiPageType;

/**
 * Reads and writes wiki markdown under the vault root (ADR-022).
 *
 * <p>Two rules make the wiki safe to open in Obsidian while the app is running:
 * every write is atomic (temp file then rename), so a reader never sees a half-written
 * page; and every file is written with LF endings and a trailing newline, so git diffs
 * stay clean and the repo's {@code eol=lf} attribute holds.
 *
 * <p>The markdown on disk is canonical. This class never merges or patches an existing
 * file: a compile replaces the whole page, which keeps output deterministic.
 */
public final class WikiFileStore {

    /** Index page slug; also its file name at the vault root. */
    public static final String INDEX_SLUG = "index";

    private static final String MARKDOWN_SUFFIX = ".md";

    /** Slugs are generated by {@link WikiSlugger}; this guards against path traversal. */
    private static final Pattern SAFE_SLUG = Pattern.compile("^[a-z0-9][a-z0-9-]*$");

    private final Path wikiRoot;

    /**
     * Creates a store rooted at a directory, creating it if needed.
     *
     * @param root absolute vault directory, e.g. {@code ./data/wiki}
     */
    public WikiFileStore(Path root) {
        this.wikiRoot = root.toAbsolutePath().normalize();
        try {
            Files.createDirectories(this.wikiRoot);
        } catch (IOException e) {
            throw new UncheckedIOException("Failed to create wiki directory: " + this.wikiRoot, e);
        }
    }

    /**
     * The vault root directory.
     *
     * @return absolute, normalised path
     */
    public Path root() {
        return wikiRoot;
    }

    /**
     * Resolves the file a page lives in.
     *
     * @param pageType page type, which selects the subfolder
     * @param slug page slug
     * @return the file path, whether or not it exists yet
     */
    public Path pathFor(WikiPageType pageType, String slug) {
        return wikiRoot.resolve(pageType.folder()).resolve(requireSafeSlug(slug) + MARKDOWN_SUFFIX);
    }

    /**
     * Writes a page atomically.
     *
     * @param pageType page type, which selects the subfolder
     * @param slug page slug
     * @param markdown page content
     * @return the path written
     */
    public Path write(WikiPageType pageType, String slug, String markdown) {
        return writeAtomically(pathFor(pageType, slug), markdown);
    }

    /**
     * Writes the generated index at the vault root.
     *
     * @param markdown index page content
     * @return the path written
     */
    public Path writeIndex(String markdown) {
        return writeAtomically(wikiRoot.resolve(INDEX_SLUG + MARKDOWN_SUFFIX), markdown);
    }

    /**
     * Reads a page back from disk.
     *
     * @param pageType page type, which selects the subfolder
     * @param slug page slug
     * @return the file content, or empty when the page has not been compiled
     */
    public Optional<String> read(WikiPageType pageType, String slug) {
        Path path = pathFor(pageType, slug);
        if (!Files.isRegularFile(path)) {
            return Optional.empty();
        }
        try {
            return Optional.of(Files.readString(path, StandardCharsets.UTF_8));
        } catch (IOException e) {
            throw new UncheckedIOException("Failed to read wiki page: " + path, e);
        }
    }

    /**
     * Deletes a page if present.
     *
     * @param pageType page type, which selects the subfolder
     * @param slug page slug
     * @return true when a file was removed
     */
    public boolean delete(WikiPageType pageType, String slug) {
        try {
            return Files.deleteIfExists(pathFor(pageType, slug));
        } catch (IOException e) {
            throw new UncheckedIOException("Failed to delete wiki page: " + slug, e);
        }
    }

    private Path writeAtomically(Path target, String markdown) {
        Path parent = target.getParent();
        if (parent == null) {
            throw new UncheckedIOException(new IOException("Wiki page path has no parent: " + target));
        }
        try {
            Files.createDirectories(parent);
            Path temp = Files.createTempFile(parent, ".wiki-", ".tmp");
            Files.writeString(temp, normalise(markdown), StandardCharsets.UTF_8);
            move(temp, target);
            return target;
        } catch (IOException e) {
            throw new UncheckedIOException("Failed to write wiki page: " + target, e);
        }
    }

    // Prefer an atomic rename; fall back for filesystems that cannot do one.
    private static void move(Path source, Path target) throws IOException {
        try {
            Files.move(source, target, StandardCopyOption.REPLACE_EXISTING, StandardCopyOption.ATOMIC_MOVE);
        } catch (AtomicMoveNotSupportedException e) {
            Files.move(source, target, StandardCopyOption.REPLACE_EXISTING);
        }
    }

    /**
     * Forces LF line endings and a single trailing newline.
     *
     * @param markdown raw content, may use CRLF
     * @return normalised content
     */
    static String normalise(String markdown) {
        String lf = markdown.replace("\r\n", "\n").replace('\r', '\n');
        return lf.endsWith("\n") ? lf : lf + "\n";
    }

    private static String requireSafeSlug(String slug) {
        if (slug == null || !SAFE_SLUG.matcher(slug).matches()) {
            throw new IllegalArgumentException("Unsafe wiki slug: " + slug);
        }
        return slug;
    }
}
